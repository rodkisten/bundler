import path from "node:path";
import { build as viteBuild, type Plugin } from "vite";
import { cipoVite } from "@rodkisten/cipo/vite";
import { devtoolsCipoConfigCss } from "../../devtools/cipo-config";
import { maquinaCipoConfigCss } from "../../maquina/cipo-config";
import type { RootEntry } from "../config";
import { DIST_DIR, ROOT_DIR } from "../config";
import { buildInfoVite } from "../vite-build-info";
import { createBrowserLibraryConfig } from "../vite/shared-config";
import { buildStep } from "./logger";

export async function buildBrowserBundles(entries: RootEntry[]): Promise<string[]> {
  const outputs: string[] = [];

  for (const entry of entries) {
    outputs.push(...await buildBrowserEntry(entry));
  }

  return outputs;
}

async function buildBrowserEntry(entry: RootEntry): Promise<string[]> {
  const plugins = createEntryPlugins(entry);
  const banner = createBanner(entry);
  const files = [
    { fileName: `${entry.name}.iife.js`, minify: false },
    { fileName: `${entry.name}.iife.min.js`, minify: true },
  ] as const;

  for (const output of files) {
    await buildStep(`Vite ${entry.name} → ${output.fileName}`, async () => {
      await viteBuild(createBrowserLibraryConfig({
        root: ROOT_DIR,
        entry: entry.absolutePath,
        outDir: DIST_DIR,
        globalName: entry.globalName,
        fileName: output.fileName,
        minify: output.minify,
        exports: entry.name === "devtools" ? "default" : "named",
        banner,
        plugins,
      }));
    });
  }

  return files.map((output) => output.fileName);
}

function createEntryPlugins(entry: RootEntry): Plugin[] {
  const plugins: Plugin[] = [buildInfoVite({ packageName: entry.name })];
  const configCss = entry.name === "devtools" ? devtoolsCipoConfigCss : entry.name === "maquina" ? maquinaCipoConfigCss : null;

  if (configCss) {
    plugins.push(cipoVite({
      root: ROOT_DIR,
      mode: "build",
      enabled: true,
      cssDelivery: "style-tag",
      configCss,
      cssFileName: `${entry.name}.compiled.css`,
      manifestFileName: `${entry.name}.cipo.compiled.manifest.json`,
      compileFabrica: true,
      transformCssTag: true,
    }));
  }

  return plugins;
}

function createBanner(entry: RootEntry): string {
  const source = path.relative(ROOT_DIR, entry.absolutePath).replace(/\\/g, "/");
  return `/*! ${entry.tool.name} | ${entry.tool.description} | source: ${source} | generated by Vite 8 */`;
}
